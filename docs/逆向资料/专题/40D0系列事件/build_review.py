def classify(va, f):
    ea = int(va, 16)
    files = {Path(p).name for p in sources[va]}
    if va in manual:
        return manual[va]
    if 'bridges.json' in files:
        return '复用已审阅', '事件注册桥的栈参数与目标跳板已归档。', '桥接之外的网络生命周期未在本函数确认'
    return '仅导出', '已保存当前IDA函数指令、伪代码及调用关系。', '未进行完整语义闭环审阅'

