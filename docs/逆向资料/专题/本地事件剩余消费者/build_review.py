PARTIAL = {
    0x65cc00, 0x65cf40, 0x67d340, 0x7c0c50, 0x7c3220, 0x7cea20,
    0x7cdf30, 0x7ce240, 0x7ce3f0, 0x7e73f0, 0x7f74b0,
    0x7f85c0, 0x800a50, 0x7f5d50, 0x70d150, 0x720660,
}


def main():
    notes = {int(line.split("|", 1)[0], 16): line.split("|", 1)[1]
             for line in NOTES.splitlines() if line.strip()}
    sources = {}
    for source in sorted((HERE / "证据").glob("*.json")):
        for function in json.loads(source.read_text(encoding="utf-8")).get("functions", []):
            sources.setdefault(int(function["va"], 16), []).append("证据/" + source.name)
    assert notes.keys() == sources.keys(), (notes.keys() - sources.keys(), sources.keys() - notes.keys())
    reviews = [{"va": hex(ea), "status": "部分分析" if ea in PARTIAL else "局部语义已审阅",
                "conclusion": notes[ea], "unknown": (
                    "仅本专题所列分支；其他分支、全部间接调用和动态业务结果未恢复。" if ea in PARTIAL
                    else "尚未动态运行验证；完整生命周期、异常输入与上游约束不因局部语义成立而视为完成。"),
                "evidence": sources[ea]} for ea in sorted(notes)]
    (HERE / "函数审阅清单.json").write_text(json.dumps({"functions": reviews}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("逐函数清单：", len(reviews))


if __name__ == "__main__":
    main()
