def main():
    rows = []
    for name in ('reused_raw.json', 'closure_raw.json', 'consumer_raw.json', 'helpers_raw.json', 'leaves_raw.json'):
        raw = json.loads((HERE / '证据' / name).read_text('utf-8'))
        for function in raw['functions']:
            status, conclusion, unknown = REVIEWS[function['va']]
            rows.append(dict(va=function['va'], status=status,
                             byte_status='声明块和指令范围均导出；离线当前PE一致',
                             reviewed_scope=conclusion, conclusion=conclusion, unknown=unknown,
                             evidence='证据/' + name + '#' + function['va'],
                             declared_chunks=function['declared_chunks']))
    assert {item['va'] for item in rows} == set(REVIEWS)
    result = dict(scope='只将逐项reviewed_scope纳入本批语义结论；完整字节通过不自动升级完整业务语义。',
                  functions=sorted(rows, key=lambda item: int(item['va'], 16)))
    (HERE / '函数审阅清单.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n', 'utf-8')
    print(dict(functions=len(rows)))


if __name__ == '__main__':
    main()
